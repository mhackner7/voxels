impl std::fmt::Display for KBMcode {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let str: &'static str = (*self).into();
        write!(f, "{}", str)
    }
}

impl Display for State {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let str = if *self == Self::Pressed {
            "Pressed"
        } else {
            "Released"
        };

        write!(f, "{str}")
    }
}

