impl From<KBMcode> for bool {
    fn from(value: KBMcode) -> Self {
        value as u8 != KBMcode::NULLorCOUNT as u8
    }
}

impl From<winit::event::ElementState> for State {
    fn from(value: winit::event::ElementState) -> Self {
        match value {
            winit::event::ElementState::Pressed => State::Pressed,
            winit::event::ElementState::Released => State::Released,
        }
    }
}

impl From<MouseScrollDelta> for KBMcode {
    fn from(value: MouseScrollDelta) -> Self {
        let delta = match value {
            MouseScrollDelta::LineDelta(_, y) => y,
            MouseScrollDelta::PixelDelta(val) => val.y as f32,
        };

        if delta.is_sign_positive() {
            KBMcode::MouseScrollUp
        } else {
            Self::MouseScrollDown
        }
    }
}

impl From<MouseButton> for KBMcode {
    fn from(value: MouseButton) -> Self {
        match value {
            MouseButton::Left => KBMcode::MouseLeft,
            MouseButton::Right => KBMcode::MouseRight,
            MouseButton::Middle => KBMcode::MouseMiddle,
            MouseButton::Forward => KBMcode::MouseForward,
            MouseButton::Back => KBMcode::MouseBack,
            MouseButton::Other(id) => match id {
                0 => KBMcode::MouseButton0,
                1 => KBMcode::MouseButton1,
                2 => KBMcode::MouseButton2,
                3 => KBMcode::MouseButton3,
                4 => KBMcode::MouseButton4,
                5 => KBMcode::MouseButton5,
                6 => KBMcode::MouseButton6,
                7 => KBMcode::MouseButton7,
                8 => KBMcode::MouseButton8,
                9 => KBMcode::MouseButton9,
                _ => KBMcode::NULLorCOUNT,
            },
        }
    }
}

